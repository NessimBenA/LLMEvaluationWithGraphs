import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Final

from CleanJsons import DEFAULT_REPLY_DIR, STANDARDIZED_PREFIX, StandardGraph, standardize_reply

DEFAULT_IMAGE_DIR: Final = "graph_images"
DEFAULT_FORMAT: Final = "svg"
FORMATS: Final = ("png", "svg", "pdf", "jpg", "gif")
RETRY_SUFFIX: Final = re.compile(r"_retry_(\d+)\.json$")
TITLE_FONT_SIZE: Final = "18"
GRAPH_ATTR: Final = {
    "splines": "curved",
    "overlap": "prism",
    "pad": "0.5",
    "dpi": "300",
    "bgcolor": "#fdfcf8",
    "fontname": "Helvetica",
    "fontsize": "18",
    "outputorder": "edgesfirst",
    "esep": "15",
    "sep": "+15,+15",
}
NODE_ATTR: Final = {
    "shape": "box",
    "style": "filled",
    "fillcolor": "#f5f5dc",
    "color": "#5d4037",
    "penwidth": "1.5",
    "fontname": "Helvetica",
    "fontsize": "11",
    "fontcolor": "#4e342e",
}
EDGE_ATTR: Final = {
    "color": "#8d6e63A0",
    "penwidth": "1.0",
    "arrowsize": "0.7",
    "fontsize": "9",
    "fontname": "Helvetica",
    "fontcolor": "#8d6e63",
}


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def title_from_filename(filename: str) -> str:
    match = RETRY_SUFFIX.search(filename)
    if match is None or not filename.startswith(STANDARDIZED_PREFIX):
        return Path(filename).stem.replace("_", " ").strip()
    core = filename[len(STANDARDIZED_PREFIX) : match.start()]
    concept, separator, model = core.rpartition("_")
    if not separator:
        return core.replace("_", " ")
    return f"Knowledge Graph for '{concept.replace('_', ' ').strip()}'\nGenerated by: {model}"


def attribute_block(kind: str, attributes: dict[str, str]) -> list[str]:
    return [f"  {kind} [", ",\n".join(f'    {key}="{value}"' for key, value in attributes.items()), "  ];", ""]


def graph_to_dot(graph: StandardGraph, title: str) -> str:
    lines = ["digraph G {"]
    lines += attribute_block("graph", {**GRAPH_ATTR, "label": escape(title), "fontsize": TITLE_FONT_SIZE})
    lines += attribute_block("node", NODE_ATTR)
    lines += attribute_block("edge", EDGE_ATTR)
    lines += [f'  "{escape(node["id"])}" [label="{escape(node["label"])}"];' for node in graph["nodes"]]
    lines.append("")
    for edge in graph["edges"]:
        label = f' [label="{escape(edge["label"])}"]' if edge["label"] else ""
        lines.append(f'  "{escape(edge["source"])}" -> "{escape(edge["target"])}"{label};')
    lines.append("}")
    return "\n".join(lines)


def render(dot_source: str, output_path: Path, image_format: str) -> str:
    result = subprocess.run(
        ["dot", f"-T{image_format}", "-o", str(output_path)],
        input=dot_source.encode("utf-8"),
        capture_output=True,
        check=False,
    )
    return "" if result.returncode == 0 else result.stderr.decode("utf-8", errors="replace").strip()


def main() -> None:
    parser = argparse.ArgumentParser(description="Draw every standardized knowledge graph with Graphviz (dot layout).")
    parser.add_argument("input_dir", nargs="?", default=DEFAULT_REPLY_DIR, help=f"Folder with the standardized_*.json files (default: {DEFAULT_REPLY_DIR}).")
    parser.add_argument("output_dir", nargs="?", default=DEFAULT_IMAGE_DIR, help=f"Folder for the images (default: {DEFAULT_IMAGE_DIR}).")
    parser.add_argument("-fmt", "--format", default=DEFAULT_FORMAT, choices=FORMATS, help=f"Image format (default: {DEFAULT_FORMAT}).")
    parser.add_argument("-f", "--force", action="store_true", help="Overwrite images that already exist.")
    parser.add_argument("--skip_errors", action="store_true", help="Keep going after a graph fails to render.")
    args = parser.parse_args()
    input_dir = Path(str(args.input_dir))
    output_dir = Path(str(args.output_dir))
    image_format = str(args.format)
    force = bool(args.force)
    skip_errors = bool(args.skip_errors)
    if not input_dir.is_dir():
        sys.exit(f"Input folder not found: {input_dir}")
    if output_dir.exists() and not output_dir.is_dir():
        sys.exit(f"Output path exists and is not a folder: {output_dir}")
    if shutil.which("dot") is None:
        sys.exit("Graphviz 'dot' was not found on PATH. Install Graphviz: https://graphviz.org/download/")
    output_dir.mkdir(parents=True, exist_ok=True)
    rendered = 0
    existing = 0
    failed = 0
    for path in sorted(input_dir.glob(f"{STANDARDIZED_PREFIX}*.json")):
        output_path = output_dir / f"{path.stem[len(STANDARDIZED_PREFIX):]}.{image_format}"
        if output_path.exists() and not force:
            existing += 1
            print(f"Exists   {output_path.name} (use -f to overwrite)")
            continue
        graph, reason = standardize_reply(path.read_text(encoding="utf-8"))
        error = reason if graph is None else render(graph_to_dot(graph, title_from_filename(path.name)), output_path, image_format)
        if error:
            failed += 1
            print(f"Failed   {path.name}: {error}")
            if not skip_errors:
                break
            continue
        rendered += 1
        print(f"Rendered {output_path.name}")
    print(f"\n{rendered} rendered, {existing} already there, {failed} failed.")
    if failed and not skip_errors:
        sys.exit("Stopped at the first failure. Use --skip_errors to render the rest.")


if __name__ == "__main__":
    main()
